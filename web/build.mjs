// Builds AgendApp from src/:
//   - dist/AgendApp.html: desktop version, one self-contained file (styles, script and font inlined);
//   - ../android/app/src/main/assets/www/: the interface embedded in the Android app;
//   - icons: Material Symbols Rounded for the interface (src/ui/icons.gen.json), the Android
//     widgets and shortcuts, and the watch app (XML drawables).
// Usage: npm run build            (everything)
//        npm run build -- --web   (without regenerating the Android drawables)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import esbuild from 'esbuild';
import svgpath from 'svgpath';

const require = createRequire(import.meta.url);
const here = path.dirname(fileURLToPath(import.meta.url));
const ANDROID = path.resolve(here, '../android');
const ASSETS = path.join(ANDROID, 'app/src/main/assets/www');
const DIST = path.join(here, 'dist');
const webOnly = process.argv.includes('--web');

function must(cond, msg) {
  if (!cond) { console.error('FAILED: ' + msg); process.exit(1); }
}

// ---------- Icons ----------
const symDir = path.join(path.dirname(require.resolve('@material-symbols/svg-400/package.json')), 'rounded');
const symbolPath = (name) => {
  const svg = fs.readFileSync(path.join(symDir, name + '.svg'), 'utf8');
  const d = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join('');
  must(d, `empty icon ${name}`);
  return d;
};
// Material viewBox (0 -960 960 960) → the 24 viewBox of the Icon component.
const to24 = (name) => svgpath(symbolPath(name)).translate(0, 960).scale(0.025).round(2).toString();

// Short interface names → Material Symbols.
const UI_ICONS = {
  calendar: 'calendar_month', list: 'view_agenda', gear: 'settings', plus: 'add', minus: 'remove',
  chevL: 'chevron_left', chevR: 'chevron_right', chevD: 'keyboard_arrow_down', chevU: 'keyboard_arrow_up',
  check: 'check', x: 'close', trash: 'delete', edit: 'edit', copy: 'content_copy', download: 'download',
  upload: 'upload', undo: 'undo', bolt: 'bolt', user: 'person', pause: 'pause', play: 'play_arrow',
  camera: 'photo_camera', qr: 'qr_code_2', chart: 'bar_chart', users: 'group', clock: 'schedule',
  moon: 'dark_mode', sun: 'light_mode', alert: 'warning', info: 'info', tag: 'sell', grip: 'drag_indicator',
  arrowUp: 'arrow_upward', arrowDown: 'arrow_downward', share: 'share', link: 'link', repeat: 'repeat',
  wand: 'wand_stars', filter: 'filter_list', eye: 'visibility', more: 'more_vert', search: 'search',
  folder: 'folder_open', backup: 'backup', lock: 'fingerprint', widgets: 'widgets', watch: 'watch',
  language: 'language',
};

const icons = {};
for (const [key, name] of Object.entries(UI_ICONS)) icons[key] = to24(name);
fs.writeFileSync(path.join(here, 'src/ui/icons.gen.json'), JSON.stringify(icons));

// Active tab: filled icon (M3 navigation bar), injected into m3.css.
const TAB_ICONS = ['calendar', 'list', 'gear'];
const tabFillCss = TAB_ICONS.map((k, i) =>
  `.tab:nth-child(${i + 1})[aria-current='page'] .ico path { d: path('${to24(UI_ICONS[k] + '-fill')}'); }`).join('\n');

const vector = (name, fill) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by web/build.mjs (Material Symbols Rounded "${name}"). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp" android:height="24dp" android:viewportWidth="960" android:viewportHeight="960">
    <group android:translateY="960">
        <path android:fillColor="${fill}" android:pathData="${symbolPath(name)}" />
    </group>
</vector>
`;
function writeDrawables(dir, map, fill) {
  fs.mkdirSync(dir, { recursive: true });
  for (const [file, name] of Object.entries(map)) fs.writeFileSync(path.join(dir, file + '.xml'), vector(name, fill));
}
if (!webOnly && fs.existsSync(ANDROID)) {
  // Widgets (white, tinted in the layouts).
  writeDrawables(path.join(ANDROID, 'app/src/main/res/drawable'), {
    ic_w_add: 'add', ic_w_sync: 'sync', ic_w_agenda: 'view_agenda', ic_w_backup: 'backup', ic_w_prev: 'chevron_left',
    ic_w_next: 'chevron_right', ic_w_today: 'today', ic_w_calendar: 'calendar_month', ic_w_lock: 'lock-fill',
    ic_w_event: 'event_upcoming', ic_w_settings: 'settings',
  }, '#FFFFFFFF');
  // Launcher shortcuts (foreground of the adaptive icons).
  writeDrawables(path.join(ANDROID, 'app/src/main/res/drawable'), {
    sc_fg_new: 'add', sc_fg_agenda: 'view_agenda', sc_fg_sync: 'sync', sc_fg_backup: 'backup',
  }, '@color/icon_fg');
  // Watch app.
  writeDrawables(path.join(ANDROID, 'wear/src/main/res/drawable'), {
    ic_calendar: 'calendar_month', ic_event: 'event', ic_settings: 'settings', ic_sync: 'sync', ic_phone: 'mobile_arrow_right',
    ic_prev: 'chevron_left', ic_next: 'chevron_right', ic_group: 'group', ic_schedule: 'schedule', ic_today: 'today',
    ic_palette: 'palette', ic_visibility_off: 'visibility_off', ic_date_range: 'date_range', ic_bar_chart: 'bar_chart',
    ic_bedtime: 'bedtime', ic_notes: 'notes', ic_upcoming: 'event_upcoming', ic_check: 'check', ic_timer: 'timer',
  }, '#FFFFFFFF');
}

// ---------- Script and styles ----------
const result = await esbuild.build({
  entryPoints: [path.join(here, 'src/main.jsx')],
  bundle: true,
  write: false,
  minify: true,
  format: 'iife',
  target: ['chrome100', 'firefox100', 'safari15'],
  jsx: 'automatic',
  jsxImportSource: 'preact',
  legalComments: 'none',
  logLevel: 'warning',
});
const js = result.outputFiles[0].text;
let css = fs.readFileSync(path.join(here, 'src/styles/m3.css'), 'utf8');
must(css.includes('/*@TAB_FILL@*/'), 'filled tab icon placeholder in m3.css');
css = css.replace('/*@TAB_FILL@*/', tabFillCss);

const page = ({ head, script }) => `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="color-scheme" content="light dark">
<title>AgendApp</title>
<link rel="icon" href="data:,">
${head}
</head>
<body>
<div id="app"></div>
<div id="layers"></div>
${script}
</body>
</html>
`;
const safeScript = (s) => s.replace(/<\/script/gi, '<\\/script');

// Android app: separate files, fonts served from assets/www/fonts.
if (fs.existsSync(ANDROID)) {
  fs.rmSync(ASSETS, { recursive: true, force: true });
  fs.mkdirSync(path.join(ASSETS, 'fonts'), { recursive: true });
  fs.writeFileSync(path.join(ASSETS, 'm3.css'), css);
  fs.writeFileSync(path.join(ASSETS, 'app.js'), js);
  fs.writeFileSync(path.join(ASSETS, 'index.html'), page({
    head: '<link rel="stylesheet" href="m3.css">',
    script: '<script src="app.js"></script>',
  }));
  for (const f of fs.readdirSync(path.join(here, 'fonts'))) {
    if (f.endsWith('.woff2')) fs.copyFileSync(path.join(here, 'fonts', f), path.join(ASSETS, 'fonts', f));
  }
}

// Desktop: a single file with the Latin font inlined (extended characters fall back to the system font).
const latin = fs.readFileSync(path.join(here, 'fonts/google-sans-flex-latin.woff2')).toString('base64');
const pcCss = css
  .replace(/url\(fonts\/google-sans-flex-latin\.woff2\)/g, `url(data:font/woff2;base64,${latin})`)
  .replace(/@font-face\s*{[^}]*latin-ext[^}]*}/g, '');
fs.mkdirSync(DIST, { recursive: true });
fs.writeFileSync(path.join(DIST, 'AgendApp.html'), page({
  head: `<style>${pcCss}</style>`,
  script: `<script>${safeScript(js)}</script>`,
}));

const kb = (n) => `${Math.round(n / 1024)} KB`;
console.log(`OK: script ${kb(js.length)}, AgendApp.html ${kb(fs.statSync(path.join(DIST, 'AgendApp.html')).size)}`);
